"""Compare the replayed outputs with the copies in expected/ (the files used to build the manuscript).

Tables, the macro file and the values plotted in each figure must match exactly. Figure files are compared byte for byte; when the bytes differ (other fonts,
other matplotlib build), PNGs are compared pixel by pixel and the largest difference is reported. The headline check
is compared number by number, and the derived result files that reproduce.sh regenerates into regenerated/ are compared
with the shipped copies. Exit code 1 if a table, a number, the headline check or a regenerated file differs.
"""
import hashlib
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIGS = ["fig1", "fig1b", "fig2", "fig2c", "fig3", "fig3b", "fig4", "fig5", "fig6"]  # figures/cl/, as printed
EXACT = ["paper/cf_numbers.tex", "paper/supp_table1_cl.tex"]


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def numbers(o, prefix=""):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from numbers(v, f"{prefix}/{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from numbers(v, f"{prefix}[{i}]")
    elif isinstance(o, (int, float)) and not isinstance(o, bool):
        yield prefix, float(o)
    else:
        yield prefix, o


def main():
    bad = 0
    for rel in EXACT:
        a, b = os.path.join(ROOT, rel), os.path.join(ROOT, "expected", rel)
        ok = os.path.exists(a) and sha(a) == sha(b)
        bad += not ok
        print(f"{'identical' if ok else 'DIFFERENT':10s} {rel}")
    from PIL import Image
    for f in FIGS:
        rel = f"figures/cl/check/{f}_values.json"
        a, b = os.path.join(ROOT, rel), os.path.join(ROOT, "expected", rel)
        ok = os.path.exists(a) and json.load(open(a)) == json.load(open(b))
        bad += not ok
        print(f"{'identical' if ok else 'DIFFERENT':10s} {rel} (plotted values)")
        for ext in ("pdf", "png"):
            rel = f"figures/cl/{f}.{ext}"
            a, b = os.path.join(ROOT, rel), os.path.join(ROOT, "expected", rel)
            if not os.path.exists(a):
                print(f"{'MISSING':10s} {rel}")
                bad += 1
            elif sha(a) == sha(b):
                print(f"{'identical':10s} {rel}")
            elif ext == "pdf":
                print(f"{'differs':10s} {rel} (compare the PNG)")
            else:
                x, y = np.asarray(Image.open(a).convert("L"), float), np.asarray(Image.open(b).convert("L"), float)
                d = np.abs(x - y) if x.shape == y.shape else None
                print(f"{'differs':10s} {rel} " + (f"(size {x.shape} vs {y.shape})" if d is None else
                                                    f"(pixels differing: {(d > 0).mean():.2%}, max grey difference {d.max():.0f})"))
    a = json.load(open(os.path.join(ROOT, "results/datadecide/verify_headline.json")))
    b = json.load(open(os.path.join(ROOT, "expected/verify_headline.json")))
    na, nb = dict(numbers(a)), dict(numbers(b))
    diff = [k for k in set(na) | set(nb)
            if not (k in na and k in nb and (na[k] == nb[k] or (isinstance(na[k], float) and isinstance(nb[k], float)
                                                                 and abs(na[k] - nb[k]) <= 1e-9 * max(1, abs(nb[k])))))]
    bad += bool(diff)
    print(f"{'identical' if not diff else 'DIFFERENT':10s} results/datadecide/verify_headline.json "
          f"({len(nb)} values{'' if not diff else f'; {len(diff)} differ, e.g. {sorted(diff)[:3]}'})")
    # derived result files regenerated by reproduce.sh into regenerated/, against the shipped copies
    for new, old in (("score80.json", "results/curve_forecast/score80.json"),
                     ("score_stage3.json", "results/curve_forecast/stage3/score_stage3.json"),
                     ("evalset_rate_test.json", "results/datadecide/evalset_rate_test.json"),
                     ("rate_variance_checks.json", "results/datadecide/rate_variance_checks.json"),
                     ("midscale_rate_verify.json", "results/midscale_rate_verify.json"),
                     ("best_cells.txt", "results/midscale_vocab/best_cells.txt"),
                     ("limisiewicz2026_refit.json", "results/external/limisiewicz2026_refit.json"),
                     ("bench_mismatch_score.json", "results/bench_mismatch_score/score.json"),
                     ("outcomes_1B_final_by_seed.csv", "results/bench_mismatch_score/outcomes_1B_final_by_seed.csv")):
        a, b = os.path.join(ROOT, "regenerated", new), os.path.join(ROOT, old)
        if not os.path.exists(a):
            print(f"{'MISSING':10s} regenerated/{new}")
            bad += 1
        elif sha(a) == sha(b):
            print(f"{'identical':10s} {old} (regenerated)")
        elif new.endswith(".json"):
            # the scorer stamps its run time; every other value must agree to 1e-12 (relative)
            na, nb = dict(numbers(json.load(open(a)))), dict(numbers(json.load(open(b))))
            diff = [k for k in set(na) | set(nb) if k != "/created_utc"
                    and not (k in na and k in nb and (na[k] == nb[k] or (isinstance(na[k], float) and isinstance(nb[k], float)
                                                                         and abs(na[k] - nb[k]) <= 1e-12 * max(1, abs(nb[k])))))]
            bad += bool(diff)
            print(f"{'equal' if not diff else 'DIFFERENT':10s} {old} (regenerated; {len(nb)} values"
                  f"{', run time stamp aside' if not diff else f'; {len(diff)} differ, e.g. {sorted(diff)[:3]}'})")
        else:
            print(f"{'DIFFERENT':10s} {old} (regenerated)")
            bad += 1
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()

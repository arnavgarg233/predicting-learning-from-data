import csv  # noqa: E402
with open(ROOT / "results/costmatch/pareto_points.csv", "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["set", "family", "n", "method", "label", "flops_mean", "flops_median", "flops_frac_target_median", "rmse", "rmse_lo",
                "rmse_hi", "median_abs", "max_abs", "ratio_vs_A3", "ratio_lo", "ratio_hi", "pareto_rmse", "pareto_worst"])
    for s, fams in S["blocks"].items():
        for fam, b in fams.items():
            for m, v in b["methods"].items():
                r = v.get("ratio_vs_A3", [None] * 3)
                w.writerow([s, fam, b["n"], m, LABEL.get(m, m), v["flops_mean"], v["flops_median"], v["flops_frac_target"], v["rmse"],
                            *v["rmse_ci95"], v["median_abs"], v["max_abs"], *r, m in b["pareto_rmse"], m in b["pareto_max_abs"]])
    for size, blk in S["osr"].items():
        for a in ("F_ext", "F_ext_flat", "C", "P2e", "P2"):
            v = blk[a]
            w.writerow([f"osr_{size}", "all", v["n"], a, a, v["flops"], v["flops"], v["flops_frac_full_run"], v["whole_rmse"], "", "",
                        v["whole_median"], v["whole_max"], "", "", "", "", ""])

def f(x, d=3):
    return "-" if x is None else f"{x:.{d}f}"


def table(name, b, keep=None):
    ms = b["methods"]
    keys = sorted(ms, key=lambda m: (ms[m]["flops_mean"], ms[m]["rmse"]))
    if keep:
        keys = [k for k in keys if k in keep]
    print(f"\n#### {name} (n = {b['n']}; target run {b['target_flops_median']:.2g} FLOPs)\n")
    print("| method | FLOPs (mean) | x target (median) | RMSE (95% CI) | median abs | worst | ratio to A3 (95% CI) | closer than A3 | Pareto |")
    print("|---|---|---|---|---|---|---|---|---|")
    for m in keys:
        v = ms[m]
        r = v.get("ratio_vs_A3")
        rs = f"{r[0]:.2f} ({r[1]:.2f}-{r[2]:.2f})" if r else "-"
        p = ("R" if m in b["pareto_rmse"] else "") + ("W" if m in b["pareto_max_abs"] else "")
        print(f"| {LABEL.get(m, m)} | {v['flops_mean']:.2g} | {v['flops_frac_target']:.2f} | {f(v['rmse'])} ({f(v['rmse_ci95'][0])}-{f(v['rmse_ci95'][1])}) "
              f"| {f(v['median_abs'])} | {f(v['max_abs'])} | {rs} | {v.get('closer_than_A3', '-')} | {p} |")


print("# Costmatch tables (generated by scripts/costmatch/tables.py)")

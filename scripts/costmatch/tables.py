print("\nPareto: R = not dominated on (mean FLOPs per corpus, RMSE); W = not dominated on (mean FLOPs, worst error).")
for s, fams in S["blocks"].items():
    for fam, b in fams.items():
        if b["n"]:
            table(f"{s} / {fam}", b)

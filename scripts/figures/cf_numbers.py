"""Write paper/cf_numbers.tex: every full-curve forecast number the manuscript quotes, as LaTeX macros.

Source: results/curve_forecast/score.json (stage 1, n = 25) or, when it exists, the merged 80-corpus score
(results/curve_forecast/score80.json). Rerunning after stage 2 swaps every quoted number; \\cfInterim marks the
interim state in captions and text.
"""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
S80 = os.path.join(ROOT, "results/curve_forecast/score80.json")
S25 = os.path.join(ROOT, "results/curve_forecast/score.json")
OUT = os.path.join(ROOT, "paper/cf_numbers.tex")
ARMS = ["A0", "A1", "A2", "A3", "A4"]


def f2(x):
    return f"{x:.2f}"


def main():
    src = S80 if os.path.exists(S80) else S25
    d = json.load(open(src))
    P = d["per_corpus"]
    names = sorted(P)
    M = {}
    M["cfN"] = str(len(names))
    M["cfInterim"] = "" if src == S80 else "interim, " + str(len(names)) + " of 80 corpora"
    fam = {}
    for c in names:
        fam.setdefault(P[c]["family"], []).append(c)
    for k, f in (("Code", "code"), ("English", "english"), ("Wiki", "wiki")):
        M[f"cfN{k}"] = str(len(fam.get(f, [])))
    for b, tag in (("23", "Mid"), ("25", "Far")):
        B = d[f"budget_2_{b}"]
        for a in ARMS:
            e = np.abs([P[c]["err"][b][a] for c in names])
            M[f"cfRms{a}{tag}"] = f2(float(np.sqrt((e ** 2).mean())))
            M[f"cfMed{a}{tag}"] = f2(float(np.median(e)))
            M[f"cfMax{a}{tag}"] = f2(float(e.max()))
        for r in ("A2_over_A3", "A4_over_A3", "A0_over_A1", "A2_over_A1"):
            if r in B:
                k = r.replace("_over_", "over")
                M[f"cf{k}{tag}"] = f2(B[r]["ratio"])
                M[f"cf{k}{tag}Lo"] = f2(B[r]["ci95"][0])
                M[f"cf{k}{tag}Hi"] = f2(B[r]["ci95"][1])
        for k, f in (("Code", "code"), ("English", "english"), ("Wiki", "wiki")):
            if f in B.get("by_family", {}):
                for a in ARMS:
                    M[f"cfRms{a}{tag}{k}"] = f2(B["by_family"][f]["rms"][a])
        e2, e3, e0 = (np.abs([P[c]["err"][b][a] for c in names]) for a in ("A2", "A3", "A0"))
        M[f"cfWinsAtwo{tag}"] = str(int((e2 < e3).sum()))
        M[f"cfWinsAzero{tag}"] = str(int((e0 < e3).sum()))
    with open(OUT, "w") as fh:
        fh.write(f"% generated by scripts/figures/cf_numbers.py from {os.path.relpath(src, ROOT)}; do not edit\n")
        for k, v in M.items():
            name = k.replace("0", "Zero").replace("1", "One").replace("2", "Two").replace("3", "Three").replace("4", "Four")
            fh.write(f"\\newcommand{{\\{name}}}{{{v}}}\n")
    print(f"{len(M)} macros from {os.path.relpath(src, ROOT)} -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())

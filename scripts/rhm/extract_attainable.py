"""Write results/rhm/attainable_info.json: for each RHM setting, the attainable excess per position on the test
windows, computed from the data files by analyze.attainable_info. analyze.py reads this file when the data files
(data/rhm/<name>.npz, 100 MB in all, regenerated by make_data.py) are absent.

    python scripts/rhm/extract_attainable.py
"""
import json

import analyze as A
from make_data import SETTINGS
from rhm import RHM

out = {}
for name, (v, m, s, L, gseed) in SETTINGS.items():
    pr = json.loads((A.OUT / "pred" / f"{name}.json").read_text())
    assert (A.ROOT / pr["data"]).exists(), pr["data"]
    out[name] = A.attainable_info(name, pr, RHM(v, m, s, L, gseed), v, s, L).tolist()
(A.OUT / "attainable_info.json").write_text(json.dumps(out, indent=1))

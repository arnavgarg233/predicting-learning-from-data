    ap.add_argument("--ref_stats_bytes", type=parse_bytes, default=None)
    ap.add_argument("--tokenizer_fit_bytes", type=parse_bytes, default="2^20")
    ap.add_argument("--enc_bytes", type=parse_bytes, default=int(2 ** 23 * 1.05), help="bytes of train encoded for the learner (tok_family)")
    ap.add_argument("--no_tok", action="store_true", help="skip the bytes build")
    a = ap.parse_args()
    out = Path(a.out or ROOT / "data/mc" / a.corpus)
    ref = a.ref_stats_bytes or (2 ** 21 if a.corpus == "abc" else 2 ** 23)
    quota = dict(tokenizer_fit=a.tokenizer_fit_bytes, ref_stats=ref, valid=a.valid_bytes, test=a.test_bytes, train=a.train_bytes)
    docs = docs_file(a.file) if a.corpus == "file" else SOURCES[a.corpus]()
    man = write_splits(docs, out, quota)
    import numpy as np
    for p in ("train", "valid", "test", "ref_stats"):   # a short partition would silently change the experiment
        got = len(np.load(out / f"{p}_bytes.npy", mmap_mode="r"))
        if got < 0.98 * quota[p]:
            sys.exit(f"{a.corpus}: partition {p} has {got} of {quota[p]} bytes (stream exhausted); lower the quota or use the C4 spare")
    if not a.no_tok:
        tok = ["python", str(ROOT / "text/tok_family.py"), "--data", str(out), "--out", str(out / "tok"), "--names", "bytes",
               "--seed", "0", "--enc_bytes", str(a.enc_bytes)]
        subprocess.run(tok, check=True)
        subprocess.run(tok + ["--verify"], check=True)
    print("prepared", a.corpus, out, flush=True)



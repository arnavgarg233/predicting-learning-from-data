def docs_abc(block=8192):
    # Tunes are shorter than the reference curves' 512-token context, so consecutive unique tunes (stream order is the
    # seeded shuffle) are packed into ~8 KB documents, as the training windows already run across document boundaries.
    # Exact repeats are dropped first, so a repeated tune cannot land in two partitions.
    seen, cur, n = set(), [], 0
    for r in stream("sander-wood/irishman"):
        t = r["abc notation"]
        h = hashlib.sha1(t.encode()).hexdigest()
        if h in seen:
            continue
        seen.add(h)
        cur.append(t)
        n += len(t.encode())
        if n >= block:
            d = "\n\n".join(cur)
            yield "abc:" + hashlib.sha1(d.encode()).hexdigest(), d
            cur, n = [], 0
    if cur:
        d = "\n\n".join(cur)
        yield "abc:" + hashlib.sha1(d.encode()).hexdigest(), d



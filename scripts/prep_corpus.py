def pack(gen, prefix, block=8192):
    """Short documents (shorter than the reference curves' 512-token context) packed in stream order into ~8 KB documents, as
    for abc; the learner's training windows already run across document boundaries."""
    cur, n = [], 0
    for _, t in gen:
        cur.append(t)
        n += len(t.encode())
        if n >= block:
            d = "\n\n".join(cur)
            yield f"{prefix}:" + _h(d), d
            cur, n = [], 0
    if cur:
        d = "\n\n".join(cur)
        yield f"{prefix}:" + _h(d), d



# Code languages without a per-language config in the parquet conversion ("Code diversity and family analysis"): the
# dataset's all-languages shards (main-branch data/train-XXXXX-of-00880.parquet, config all-all) are read in order, at most
# GHC_MAX_SHARDS, filtered by the language column; each shard is downloaded once and the rows of every such language are
# extracted to data/ghc_cache (a lock directory per shard lets parallel preparations share it); then a seeded 1000-row
# shuffle buffer, as datasets' streaming shuffle. A language whose rows do not fill the quotas fails preparation.
GHC_FULL = {"Go": "GO", "Rust": "Rust", "Ruby": "Ruby", "TypeScript": "TypeScript", "Shell": "Shell", "SQL": "SQL",
            "Scala": "Scala", "Haskell": "Haskell", "Lua": "Lua", "Perl": "Perl", "Julia": "Julia", "TeX": "TeX",
            "PowerShell": "PowerShell", "Fortran": "FORTRAN", "CSS": "CSS", "Markdown": "Markdown"}
GHC_NSHARD, GHC_MAX_SHARDS = 880, 20
GHC_CACHE = ROOT / "data/ghc_cache"


def ghc_extract(i):
    """Rows of every GHC_FULL language in all-all shard i -> GHC_CACHE/<i>/<LANGUAGE>.parquet (once)."""
    import shutil
    import time
    import pyarrow as pa
    import pyarrow.compute as pc
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download
    d, lock = GHC_CACHE / f"{i:05d}", GHC_CACHE / f"{i:05d}.lock"
    GHC_CACHE.mkdir(parents=True, exist_ok=True)
    while not (d / "DONE").exists():
        try:
            lock.mkdir()
        except FileExistsError:
            if time.time() - lock.stat().st_mtime > 1800:      # stale lock of a killed preparation
                shutil.rmtree(lock, ignore_errors=True)
            time.sleep(3)
            continue
        try:
            tmp = GHC_CACHE / f"{i:05d}.dl"
            f = hf_hub_download("codeparrot/github-code-clean", f"data/train-{i:05d}-of-{GHC_NSHARD:05d}.parquet",
                                repo_type="dataset", local_dir=str(tmp))
            langs = pa.array(sorted(GHC_FULL.values()))
            parts = {v: [] for v in GHC_FULL.values()}
            for b in pq.ParquetFile(f).iter_batches(batch_size=4096, columns=["code", "repo_name", "path", "language"]):
                b = pa.Table.from_batches([b])
                b = b.filter(pc.is_in(b["language"], value_set=langs))
                for v in parts:
                    t = b.filter(pc.equal(b["language"], v))
                    if t.num_rows:
                        parts[v].append(t)
            out = GHC_CACHE / f"{i:05d}.part"
            shutil.rmtree(out, ignore_errors=True)
            out.mkdir()
            for v, ts in parts.items():
                if ts:
                    pq.write_table(pa.concat_tables(ts), out / f"{v}.parquet")
            (out / "DONE").write_text("")
            shutil.rmtree(d, ignore_errors=True)
            out.rename(d)
            shutil.rmtree(tmp, ignore_errors=True)
        finally:
            shutil.rmtree(lock, ignore_errors=True)
    return d


def _buffer_shuffle(it, n=1000, seed=STREAM_SEED):
    import numpy as np
    rng, buf = np.random.default_rng(seed), []
    for x in it:
        if len(buf) < n:
            buf.append(x)
            continue
        j = int(rng.integers(n))
        yield buf[j]
        buf[j] = x
    rng.shuffle(buf)
    yield from buf


def docs_ghc_all(language):
    import pyarrow.parquet as pq
    v = GHC_FULL[language]

    def rows():
        for i in range(GHC_MAX_SHARDS):
            p = ghc_extract(i) / f"{v}.parquet"
            if p.exists():
                t = pq.read_table(p)
                yield from zip(t["code"].to_pylist(), t["repo_name"].to_pylist(), t["path"].to_pylist())
    for code, repo, path in _buffer_shuffle(rows()):
        yield f"{language}:{repo}/{path}", code



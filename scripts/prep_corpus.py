def pile_extract():
    import shutil
    import time
    d, lock = PILE_CACHE / "sets", PILE_CACHE / "sets.lock"
    PILE_CACHE.mkdir(parents=True, exist_ok=True)
    while not (d / "DONE").exists():
        try:
            lock.mkdir()
        except FileExistsError:
            if time.time() - lock.stat().st_mtime > 3 * 3600:
                shutil.rmtree(lock, ignore_errors=True)
            time.sleep(5)
            continue
        try:
            tmp = PILE_CACHE / "sets.part"
            shutil.rmtree(tmp, ignore_errors=True)
            tmp.mkdir()
            want = {v.encode(): k for k, v in PILE_SETS.items()}
            fh = {k: open(tmp / f"{k}.jsonl", "wb") for k in PILE_SETS}
            got = {k: 0 for k in PILE_SETS}
            key = b'"pile_set_name": "'
            for shard in (0, 1):
                p = subprocess.Popen(f"curl -sL --retry 5 -A curl/8.4.0 {PILE_URL.format(shard)} | zstd -dc", shell=True,
                                     stdout=subprocess.PIPE, bufsize=1 << 22)
                for line in p.stdout:
                    i = line.rfind(key, max(0, len(line) - 120))
                    if i < 0:
                        continue
                    name = line[i + len(key):].split(b'"', 1)[0]
                    k = want.get(name)
                    if k is None or got[k] >= PILE_Q:
                        continue
                    t = json.loads(line)["text"]
                    fh[k].write(json.dumps({"text": t}).encode() + b"\n")
                    got[k] += len(t.encode())
                    if all(v >= PILE_Q for v in got.values()):
                        break
                p.kill()
                p.wait()
                if all(v >= PILE_Q for v in got.values()):
                    break
            for f in fh.values():
                f.close()
            (tmp / "counts.json").write_text(json.dumps(got))
            (tmp / "DONE").write_text("")
            shutil.rmtree(d, ignore_errors=True)
            tmp.rename(d)
        finally:
            shutil.rmtree(lock, ignore_errors=True)
    return d


def docs_pile(slug):
    d = pile_extract()

    def rows():
        with open(d / f"{slug}.jsonl") as f:
            for line in f:
                t = json.loads(line)["text"]
                yield f"{slug}:" + _h(t), t
    return _buffer_shuffle(rows())


def docs_dolma_reddit():
    def rows():
        p = subprocess.Popen(f"curl -sL --retry 5 {DOLMA_REDDIT} | gzip -dc", shell=True, stdout=subprocess.PIPE, bufsize=1 << 22)
        try:
            for line in p.stdout:
                r = json.loads(line)
                t = (r.get("text") or "").strip()
                if t:
                    yield f"reddit:{r['id']}", t
        finally:
            p.kill()
    return pack(_buffer_shuffle(rows()), "dolma_reddit")



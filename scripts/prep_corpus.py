"""Prepare one corpus of the multicorpus level test on the pod.

  python -u scripts/prep_corpus.py --corpus {code,pg19,pubmed,ja_wiki,abc,c4} [--out data/mc/<corpus>]

Streams the corpus (a seeded shuffle of the stream, deterministic), yields (doc_id, text) and calls
scripts/prep_fineweb.write_splits unchanged: documents go to tokenizer_fit / ref_stats / valid / test / train by a seeded hash of the
document id, exact and near duplicates are dropped across partitions, every document is followed by "\\n\\n", and train is written in
a seeded shuffled order so that each byte budget is a prefix. Then text/tok_family.py --names bytes writes OUT/tok in the format
scripts/train_text.py --tok_dir reads (tok_bytes_{train,ref,valid,test}.npy, tok_bytes_L.npy, tokenization_meta.json, manifest.json).

Files in OUT: {tokenizer_fit,ref_stats,valid,test,train}_bytes.npy and _docstarts.npy (plus _gpt2.npy, _docids.txt from write_splits),
meta.json, manifest.json; OUT/tok as above. Default quotas: train 9.0e6 bytes (>= 2^23 x 1.05), valid and test 2^22, ref_stats 2^23
(2^21 for abc, which has about 37 MB in all and many repeated tunes), tokenizer_fit 2^20 (unused).
Sources: code codeparrot/codeparrot-clean-valid (permissive licence, not autogenerated); pg19 emozilla/pg19 (books cut into ~8 kB
blocks at paragraph breaks); pubmed MedRAG/pubmed (contents); ja_wiki wikimedia/wikipedia 20231101.ja; abc sander-wood/irishman
('abc notation', control code dropped); c4 data/c4/c4-validation.00000-of-00008.json.gz (local, no download).
The process ends with os._exit(0): streaming datasets can hang at interpreter exit.
"""

def _ordered_blocks(rows, prefix, block=8192):
    """rows: (group, text) in dataset order; consecutive rows of one group packed into ~8 KB documents."""
    cur, n, g0, i = [], 0, None, 0
    for g, t in rows:
        if g != g0 and cur:
            yield f"{prefix}:{g0}:{i}", "\n\n".join(cur)
            cur, n, i = [], 0, i + 1
        g0 = g
        cur.append(t)
        n += len(t.encode()) + 2
        if n >= block:
            yield f"{prefix}:{g0}:{i}", "\n\n".join(cur)
            cur, n, i = [], 0, i + 1
    if cur:
        yield f"{prefix}:{g0}:{i}", "\n\n".join(cur)


